"""Generate the ASI access rules from the apworld data; --check detects drift."""
import argparse
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / "gta_3_mod/src/RuntimeData.h"


def render():
    spec = importlib.util.spec_from_file_location("gta3_data", ROOT / "archipelago_client/gta3/data.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    data = module.data
    rows, last = [], {}
    for loc in data["locations"]:
        name, chain = loc["id"], loc.get("chain")
        links = [link for link in data["mission_story_links"] if link["target"] == name]
        openers = [link["trigger"] for link in links if link["kind"] == "opens_chain"]
        parents = [link["trigger"] for link in links if link["kind"] == "replaces_previous"]
        if not parents and chain in last:
            parents = [last[chain]]
        parents += [link["trigger"] for link in links if link["kind"] == "adds_prerequisite"]
        if chain:
            last[chain] = name
        def array(values):
            assert len(values) <= 4
            return "{" + ", ".join(json.dumps(v) for v in values + [""] * (4 - len(values))) + "}"
        rows.append("    {" + ", ".join([
            json.dumps(name), json.dumps(loc["region"]),
            json.dumps(chain or ""),
            json.dumps(data["mission_unlock_by_location"].get(name, "")),
            array(openers), array(list(dict.fromkeys(parents)))]) + "},")
    return ("// Generated by gta_3_mod/tools/generate_runtime_data.py; do not edit.\n#pragma once\n"
            "namespace RuntimeData {\n"
            "struct Rule { const char* location; const char* region; const char* chain; const char* unlock; "
            "const char* openers[4]; const char* parents[4]; };\n"
            "inline constexpr Rule kRules[] = {\n" + "\n".join(rows) + "\n};\n"
            "inline constexpr const char* kItems[] = {\n" +
            "".join("    " + json.dumps(name) + ",\n" for name in data["item_ids"]) + "};\n}\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != expected:
            raise SystemExit("RuntimeData.h is stale; run python gta_3_mod/tools/generate_runtime_data.py")
    else:
        TARGET.write_text(expected, encoding="utf-8")
